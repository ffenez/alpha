package app.alpha.analysis

import kotlin.math.ceil

/**
 * Сколько нужно копить, чтобы отличие такого размера стало различимо.
 *
 * Одна формула на всё приложение: и скрининг продукта, и окно решения Поиска
 * спрашивают одно и то же — за какое время счётная погрешность станет меньше
 * искомой добавки. Двух разных ответов на этот вопрос в приложении быть не
 * должно, иначе «нужно ещё 20 с» на одном экране и «нужно 5 минут» на другом
 * означали бы разную статистику одного и того же прибора.
 *
 * При равных выдержках фона и образца σ разности скоростей ≈ √(2·R/t).
 * Приравнивая k·σ к искомой добавке p·R, получаем **t = 2k²/(p²·R)**.
 *
 * Формула говорит о СЧЁТНОЙ погрешности и ни о чём больше. Она не знает, что
 * фон сам по себе гуляет: если добавка меньше собственной изменчивости места,
 * никакое время её не «докопит» — это ограничение названо там, где считается
 * вес изученного фона.
 */
object DecisionTime {

    /**
     * @param rateCps фоновая скорость счёта, с⁻¹.
     * @param fraction искомая добавка долей от фона (0,05 = 5 %).
     * @param sigma во сколько σ отличие считается различимым.
     * @return секунды на каждый прогон; null — считать не из чего.
     */
    fun secondsFor(rateCps: Double, fraction: Double, sigma: Double = 3.0): Long? {
        if (rateCps <= 0.0 || fraction <= 0.0 || sigma <= 0.0) return null
        val seconds = 2.0 * sigma * sigma / (fraction * fraction * rateCps)
        if (!seconds.isFinite()) return null
        // Вверх: это МИНИМУМ, и «копите 287 с» вместо 288 — обещание на
        // секунду короче нужного.
        return ceil(seconds).toLong().coerceAtLeast(1L)
    }
}
