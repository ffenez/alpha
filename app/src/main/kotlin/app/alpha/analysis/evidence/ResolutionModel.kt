package app.alpha.analysis.evidence

import app.alpha.analysis.PeakDetection
import kotlin.math.sqrt

/**
 * Модель энергетического разрешения детектора: ожидаемая FWHM(E).
 *
 * Разрешение — ПАРАМЕТР движка, а не константа. Вендор заявляет для RC-110
 * 8,4 ± 0,3 % FWHM на линии Cs-137 (662 кэВ) — это одно измерение в одной
 * точке. Распространять эти проценты на весь диапазон нельзя: относительное
 * разрешение сцинтиллятора падает с ростом энергии, и «8,4 % на всех энергиях»
 * дало бы у 60 кэВ вдвое узкое окно, а у 2,6 МэВ — вдвое широкое.
 *
 * Поэтому интерфейс существует раньше, чем измерения: когда появятся
 * калибровочные точки на нескольких линиях, сюда подставляется
 * [MeasuredResolution] и весь движок начинает работать по измеренной ширине
 * без единой правки логики.
 */
fun interface ResolutionModel {

    /** Ожидаемая ширина фотопика на половине высоты, кэВ. */
    fun fwhmKeV(energyKeV: Double): Double

    /** Ожидаемая σ гауссова пика: FWHM = 2√(2 ln 2)·σ. */
    fun sigmaKeV(energyKeV: Double): Double = fwhmKeV(energyKeV) / 2.3548
}

/**
 * Модель по умолчанию — та же, что у поиска пиков: FWHM(E) = R₆₆₂·√(662·E).
 *
 * Допущение одно: разрешение определяется статистикой носителей заряда, то есть
 * ΔE ∝ √E, а относительное разрешение ∝ 1/√E. Для сцинтиллятора это ПЕРВОЕ
 * приближение: реальная FWHM²(E) содержит ещё не зависящий от энергии шум
 * тракта и вклад неоднородности светосбора, поэтому у нижнего края шкалы
 * модель занижает ширину. Единственная точка, где она привязана к прибору, —
 * заявленные вендором 8,4 % на 662 кэВ.
 *
 * @param resolution662 относительное FWHM на 662 кэВ ЭТОГО прибора
 * ([app.alpha.device.DeviceModel.peakResolution662]).
 */
class SqrtResolution(
    private val resolution662: Double = PeakDetection.RESOLUTION_662.toDouble(),
) : ResolutionModel {
    override fun fwhmKeV(energyKeV: Double): Double =
        resolution662 * sqrt(662.0 * maxOf(energyKeV, 1.0))
}

/**
 * Измеренная модель разрешения: FWHM(E) = √(a + b·E + c·E²).
 *
 * Ровно та форма, которой пользуются спектрометрические пакеты: `a` — не
 * зависящий от энергии шум тракта, `b·E` — статистика носителей, `c·E²` —
 * систематика (неоднородность светосбора, дрейф усиления).
 *
 * Коэффициентов по умолчанию у класса НЕТ и не будет: их даёт только подгонка
 * по измеренным на приборе линиям. Пока таких измерений нет, конструктор
 * никем не вызывается — это и есть честное состояние «модель не измерена».
 */
class MeasuredResolution(
    private val a: Double,
    private val b: Double,
    private val c: Double,
) : ResolutionModel {
    init {
        require(a >= 0.0) { "a must be non-negative" }
    }

    override fun fwhmKeV(energyKeV: Double): Double {
        val e = maxOf(energyKeV, 0.0)
        return sqrt(maxOf(a + b * e + c * e * e, 0.0))
    }
}
