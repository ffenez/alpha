package app.alpha.device

import app.alpha.ui.text.RuStrings
import app.alpha.ui.text.Strings

/**
 * Модель прибора и её характеристики, от которых зависит обработка.
 *
 * ## Зачем это нужно
 *
 * Протокол у серии общий (`cdump/radiacode` работает со 101/102/103/110), и
 * приложение подключается к любому прибору серии без изменений. Разные у них
 * не команды, а **физика**: кристалл, энергетический диапазон, разрешение и
 * чувствительность. Пока эти числа были константами RC-110 внутри алгоритмов,
 * приложение молча применяло к чужому прибору чужие параметры — например,
 * искало пики шириной 8,4 % там, где детектор даёт 7,4 %.
 *
 * ## Откуда берутся числа
 *
 * Из официального сравнения моделей RadiaCode (radiacode.com/compare,
 * проверено 12.08.2026). Разрешение указано на 662 кэВ (Cs-137),
 * чувствительность — тоже для Cs-137.
 *
 * ## Чего здесь СОЗНАТЕЛЬНО нет
 *
 * Числа для 101 и 102 в актуальном сравнении вендора отсутствуют, поэтому они
 * не выдуманы «по аналогии»: эти модели опознаются, но получают
 * [UNKNOWN]-профиль — консервативные значения и честная строка на экране. То
 * же для любой будущей модели: неизвестный прибор работает, просто без
 * подгонки параметров под него.
 *
 * Число каналов спектра берётся из самого спектра, а не отсюда: прибор
 * присылает его в каждом ответе, и это надёжнее любой таблицы.
 */
enum class DeviceModel(
    /** Как модель называется на экране. */
    val displayName: String,
    /**
     * Материал сцинтиллятора; null — неизвестен.
     *
     * Химическая формула («CsI(Tl)») языку интерфейса не подчиняется, а
     * «органический пластик» это слова — поэтому у пластика формулы нет, и
     * подпись собирает [crystalTitle].
     */
    val crystal: String?,
    /** Нижняя граница энергетической шкалы, кэВ. */
    val minEnergyKeV: Float,
    /** Верхняя граница энергетической шкалы, кэВ. */
    val maxEnergyKeV: Float,
    /**
     * Относительное разрешение FWHM на 662 кэВ, доля. null — прибор не
     * спектрометр (пластиковый сцинтиллятор) или разрешение не опубликовано.
     */
    val resolution662: Float?,
    /** Чувствительность: имп/с на 1 мкЗв/ч по Cs-137; null — не опубликована. */
    val cpsPerMicroSvH: Float?,
    /** У пластикового сцинтиллятора формулы нет — есть название материала. */
    val organicPlastic: Boolean = false,
) {
    /** RadiaCode 101/102 — первые модели серии; параметры не опубликованы. */
    RC_101("RadiaCode-101", crystal = null, 20f, 3000f, null, null),
    RC_102("RadiaCode-102", crystal = null, 20f, 3000f, null, null),

    RC_103("RadiaCode-103", "CsI(Tl)", 20f, 3000f, 0.084f, 30f),

    /** 103G: кристалл GAGG(Ce) — плотнее, разрешение лучше. */
    RC_103G("RadiaCode-103G", "GAGG(Ce)", 25f, 3000f, 0.074f, 40f),

    RC_110("RadiaCode-110", "CsI(Tl)", 20f, 3000f, 0.084f, 77f),

    /**
     * RadiaCode Zero: органический пластик. Спектрометрии нет — вендор
     * указывает разрешение как «N/A».
     *
     * Что из этого следует в приложении (правило — `InstrumentCapability`):
     * пики, нуклиды, радон, радиоэлементная съёмка и жёсткость для него не
     * считаются; спектрограмма рисуется, но её полосы подписаны как деление
     * шкалы прибора, а не как энергии.
     */
    ZERO("RadiaCode Zero", crystal = null, 30f, 3000f, null, 16f, organicPlastic = true),

    /** Прибор серии, который мы не опознали: работает на общих правилах. */
    UNKNOWN("RadiaCode", crystal = null, 20f, 3000f, null, null),
    ;

    /** Подпись материала на языке интерфейса; null — материал неизвестен. */
    fun crystalTitle(s: Strings = RuStrings): String? =
        crystal ?: if (organicPlastic) s.crystalOrganicPlastic else null

    /** Считает ли прибор спектр по каналам (а не просто интенсивность). */
    val isSpectrometer: Boolean get() = this != ZERO

    /**
     * Ниже этой энергии пики не ищутся, кэВ.
     *
     * Не константа одной модели, а ПРАВИЛО: первая октава над порогом
     * регистрации у любого сцинтиллятора занята самим порогом, утечками и
     * рассеянием, и структура там говорит о приборе, а не об источнике. Порог
     * у моделей разный (20 кэВ у 103 и 110, 25 у 103G, 30 у Zero), поэтому и
     * граница разная — раньше она была числом RC-110 для всех.
     */
    val peakFloorKeV: Float get() = minEnergyKeV * 2f

    /**
     * Разрешение, которым пользуется поиск пиков. У моделей без
     * опубликованного числа берётся консервативное [DEFAULT_RESOLUTION_662]:
     * более широкое окно скорее сольёт два близких пика, чем придумает лишний.
     */
    val peakResolution662: Float get() = resolution662 ?: DEFAULT_RESOLUTION_662

    companion object {

        /**
         * **Инженерный параметр**: разрешение по умолчанию для неопознанного
         * прибора — худшее из опубликованных по серии (8,4 %). Ошибиться в
         * сторону более широкого пика безопаснее: узкое окно ищет структуру
         * там, где её нет.
         */
        const val DEFAULT_RESOLUTION_662 = 0.084f

        /**
         * Модель по серийному номеру: «RC-103G-000115» → [RC_103G].
         *
         * Серийник — самый надёжный из доступных признаков: он приходит от
         * самого прибора, в отличие от имени в эфире BLE, которое человек
         * может переименовать.
         */
        fun fromSerial(serialNumber: String?): DeviceModel {
            val token = Regex("^RC-?([0-9]{3}G?|Zero)", RegexOption.IGNORE_CASE)
                .find(serialNumber?.trim().orEmpty())
                ?.groupValues?.get(1)
                ?.uppercase()
                ?: return UNKNOWN
            return when (token) {
                "101" -> RC_101
                "102" -> RC_102
                "103" -> RC_103
                "103G" -> RC_103G
                "110" -> RC_110
                "ZERO" -> ZERO
                else -> UNKNOWN
            }
        }
    }
}
