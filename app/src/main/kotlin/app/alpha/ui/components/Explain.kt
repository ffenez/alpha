package app.alpha.ui.components

import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import app.alpha.ui.text.LocalStrings
import app.alpha.ui.theme.LocalAppColors

/**
 * Переключатель «Пояснения» и три категории, на которые делится ВЕСЬ видимый
 * интерфейс.
 *
 * | категория | пояснения включены | пояснения выключены |
 * |---|---|---|
 * | критическая информация | видно | видно |
 * | основной результат и управление | видно | видно |
 * | пояснение и справка | видно | скрыто |
 *
 * **Критическая информация** — то, без чего результат нельзя истолковать
 * верно: единица, длительность измерения, неопределённость, знаменатель
 * отношения, «данных недостаточно», «нет связи», предупреждение о превышении,
 * состояние записи, отказ метода. Прячется — только через труп.
 *
 * **Основное** — сами значения, названия величин, вердикт и органы управления.
 *
 * **Пояснение** — то, что учит: как устроен расчёт, что означает термин
 * (P10–P90, σ, отношение окон), почему функция недоступна, приглашение
 * «нажмите…», расшифровка очевидного состояния. Сюда же кнопка «i», если она
 * существует ТОЛЬКО ради справки.
 *
 * ## Что переключатель не делает
 *
 * Он не меняет ни одного измерения, расчёта, порога, вердикта и набора данных.
 * Если под `if` от него оказалась логика, а не показ текста — это дефект, а не
 * настройка вида.
 *
 * ## Как этим пользоваться
 *
 * Не пишите `if (LocalHintsVisible.current)` в экранах: одиночная проверка
 * рано или поздно разъезжается с правилом. Пояснительная строка — [Hint],
 * пояснительный блок — [Explain], пояснительная кнопка справки —
 * [ExplainInfoButton].
 */
@Composable
fun Explain(content: @Composable () -> Unit) {
    if (!LocalHintsVisible.current) return
    content()
}

/**
 * Кнопка справки «i», существующая только ради пояснения: при выключенных
 * пояснениях её нет.
 *
 * Если за этой же кнопкой лежит не справка, а данные (полный отчёт, таблица,
 * снимок), она относится к основному интерфейсу и рисуется обычным [Chip] —
 * прятать её нельзя.
 */
@Composable
fun ExplainInfoButton(onClick: () -> Unit, modifier: Modifier = Modifier) {
    Explain {
        Chip(
            text = INFO_GLYPH,
            color = LocalAppColors.current.ink2,
            onClick = onClick,
            modifier = modifier,
        )
    }
}

/** Знак справки: один во всём приложении. */
const val INFO_GLYPH = "i"

/** Подпись кнопки справки для доступности. */
@Composable
fun infoLabel(): String = LocalStrings.current.hintsTitle
