package app.alpha.ui.logic

/**
 * Отклик поиска — ТРИ НЕЗАВИСИМЫХ КАНАЛА, а не один выбор из четырёх.
 *
 * ## Почему не режим
 *
 * Каналы работают через разные органы чувств и не спорят друг с другом: щелчки
 * слышны, вибрация чувствуется в кармане, тон ведёт по высоте. Человек в поле
 * хочет их СОЧЕТАТЬ — щелчки и вибрацию сразу, тон вместо щелчков, всё разом в
 * шумном месте. Взаимоисключающий выбор запрещал это без всякой причины:
 * ограничение было в модели данных, а не в приборе.
 *
 * Выключены все три — это и есть «тишина»; отдельного значения для неё не
 * нужно, потому что оно ничего не добавляет к трём выключателям.
 *
 * ## Что это НЕ трогает
 *
 * Тревогу и сигналы самого прибора. Отклик поиска — постоянная обратная связь
 * во время работы; тревога — событие превышения порога; звук и вибрация
 * прибора — его собственные, аппаратные. Три разные вещи, три разных места в
 * настройках (`settings_ui_restructure.md` §5).
 */
data class SearchFeedbackChannels(
    /** Щелчок на каждый зарегистрированный импульс. */
    val clicks: Boolean = false,
    /** Непрерывный тон, высота которого следует отношению. */
    val tone: Boolean = false,
    /** Вибрация: тот же сигнал без звука. */
    val vibro: Boolean = false,
) {

    /** Молчат все каналы — прежний режим «нет». */
    val silent: Boolean get() = !clicks && !tone && !vibro

    /** Хоть один канал звучит: от этого зависят громкость и аудио-движок. */
    val usesSound: Boolean get() = clicks || tone

    /**
     * Есть канал, который говорит об ОТНОШЕНИИ, а не о каждом импульсе.
     *
     * Тон и вибрация ведут по «теплее — холоднее», и без того, с чем
     * сравнивать, они молчат по построению; щелчки же слышны всегда, потому
     * что описывают сами импульсы.
     */
    val usesReference: Boolean get() = tone || vibro

    companion object {

        /**
         * Каналы из прежнего одиночного режима.
         *
         * Настройки, сохранённые до разделения, обязаны продолжать работать:
         * человек не должен обнаружить тишину там, где выбирал щелчки.
         */
        fun ofLegacyMode(id: String?): SearchFeedbackChannels = when (id) {
            "clicks" -> SearchFeedbackChannels(clicks = true)
            "tone" -> SearchFeedbackChannels(tone = true)
            "vibro" -> SearchFeedbackChannels(vibro = true)
            // Явное «off» — тишина; неизвестное значение (сбой хранилища) —
            // щелчки: это обычный отклик поиска, и молчащий прибор в поле
            // хуже, чем неожиданный звук.
            "off" -> SearchFeedbackChannels()
            else -> SearchFeedbackChannels(clicks = true)
        }
    }
}
