package app.alpha.ui.logic

/**
 * Отбор записей журнала по прибору.
 *
 * ## Почему запись без пометки прибора не показывается
 *
 * Пометка появилась не сразу, и у записей прежних версий прибор неизвестен.
 * Показать их при выбранном приборе значило бы приписать их ему — то есть
 * сказать о данных больше, чем о них известно. Поэтому они видны только во
 * «всех приборах», где ничего не утверждается.
 *
 * Обратное тоже верно: «все приборы» — это ОБЪЕДИНЁННЫЙ СПИСОК записей, а не
 * объединённый ряд измерений. Числовые ряды разных приборов не складываются:
 * у каждого свой кристалл и своя калибровка.
 */
object DeviceFeedFilter {

    /**
     * @param serial выбранный прибор; null — показываются все записи.
     * @param deviceOf чей прибор у записи; null — неизвестен.
     */
    fun <T> select(entries: List<T>, serial: String?, deviceOf: (T) -> String?): List<T> {
        if (serial == null) return entries
        return entries.filter { deviceOf(it) == serial }
    }
}
