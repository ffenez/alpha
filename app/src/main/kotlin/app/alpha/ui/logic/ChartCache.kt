package app.alpha.ui.logic

/**
 * Последние построенные ряды карточек Главной — на время жизни приложения.
 *
 * ## Зачем
 *
 * Переход на другую вкладку выводит Главную из композиции, и всё, что она
 * помнила через `remember`, умирает вместе с ней: возвращаясь, экран собирался
 * с нуля — пустые карточки, потом запрос в базу, потом кадры. На глаз это
 * читается как «Главная подлагивает и грузится не сразу», хотя данные уже были
 * прочитаны минуту назад.
 *
 * Здесь лежит РЕЗУЛЬТАТ последнего чтения. Возврат на вкладку рисует его
 * немедленно, а обновление приходит следом обычным путём — то есть картинка
 * появляется сразу, а свежесть догоняет.
 *
 * ## Чего здесь нет
 *
 * Ни истории, ни собственного источника правды: кэш хранит то, что УЖЕ
 * посчитано конвейером, и ничего не решает сам. Второй источник правды о
 * данных — ровно та беда, из-за которой мини-график и полноэкранный когда-то
 * разошлись.
 */
class ChartCache {

    /** Снимок и окно по величине — то, что рисовалось в последний раз. */
    var charts: Map<ChartMetric, LoadedChart> = emptyMap()

    /**
     * Куда человек увёл окно — по величине.
     *
     * Возврат на вкладку не должен сбрасывать жест; и карточка Главной, и
     * полноэкранный график берут окно ОТСЮДА, поэтому тап по карточке
     * открывает ровно то, что на ней видно, а не «пять минут по умолчанию».
     */
    var gestures: Map<ChartMetric, app.alpha.ui.chart.ChartGesture> = emptyMap()

    /** Начало истории: меняется первой записью и уборкой журнала. */
    var earliestMillis: Long? = null
}

/** Загруженный ряд одной величины: окно, снимок и прочитанный диапазон. */
data class LoadedChart(
    val window: ChartWindow,
    val snapshot: ChartSnapshot,
    /**
     * Диапазон, который реально прочитан из базы (окно плюс запас).
     *
     * По нему решается, нужен ли запрос вообще: сдвиг ВНУТРИ прочитанного —
     * это перепроецирование неизменного снимка, то есть арифметика по полутора
     * сотням колонок, а не поход в базу.
     */
    val loadedRange: ChartWindow,
    /** Начало истории на момент загрузки — чтобы кадр пересчитывал окно без базы. */
    val earliestMillis: Long?,
)
