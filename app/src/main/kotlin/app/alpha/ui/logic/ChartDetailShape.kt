package app.alpha.ui.logic

/**
 * Форма подробного ряда: что соединяется линией, а что стоит штрихом.
 *
 * ## Почему это отдельная функция, а не пара строк в рисовании
 *
 * Подробный ряд — прореживание по крайним значениям колонки. Пока колонка
 * равна агрегату снимка (одно измерение прибора), минимум и максимум — это
 * соседние измерения, и ломаная «максимум → минимум → максимум следующей»
 * совпадает с самими измерениями. Но колонка бывает шире агрегата: на длинных
 * окнах она приходит из хранения (ADR 004: колонка = час), а на средних —
 * из числа пикселей поля (шестичасовое окно на 1080 px даёт 40 с, то есть
 * сорок измерений). Тогда та же ломаная рисует равномерный рост от минимума
 * прошлой колонки к максимуму текущей и вертикальный сброс обратно — процесс,
 * которого не было.
 *
 * Поэтому связь между колонками несёт МЕДИАНА (утверждение о времени между
 * колонками), а размах колонки — вертикальный штрих в её собственном x
 * (утверждение о том, что было внутри колонки). При узкой колонке штрихи
 * стоят вплотную и картинка та же, что была; при широкой получается честный
 * график размаха вместо выдуманного тренда.
 */
object ChartDetailShape {

    /**
     * Означают ли крайние значения колонки сами измерения.
     *
     * Граница проходит по РАЗРЕШЕНИЮ ДАННЫХ, а не по ширине колонки на экране:
     * пиксели не говорят, сколько измерений в колонку попало. Колонка шириной с
     * агрегат снимка несёт одно измерение прибора, и её min = max = само
     * измерение — штриха нет, линия идёт по измерениям. Колонка шире агрегата
     * несёт их несколько, и её размах — порядковые статистики группы: на
     * шестичасовом окне при поле 1080 px колонка равна 40 с, то есть сорока
     * измерениям. Кадр строится по устойчивым границам колонок (Q10/Q90,
     * `DoseScales`), поэтому min–max сорока измерений выходит за поле: на
     * записи 1 Гц с σ/µ ≈ 13 % средний штрих занимает 79 % высоты, а
     * максимальный упирается в обе границы. Такую колонку рисует медиана с
     * квантильными конвертами.
     *
     * @param columnMillis ширина нарисованной колонки.
     * @param subBucketMillis ширина агрегата снимка — предел разрешения данных.
     * @param quantilesExact агрегат снимка — одно сырое измерение (точный путь
     *   ADR 004). На почасовых скетчах и на оценке по средним агрегат сам уже
     *   статистика, и подробного вида для него не существует.
     */
    fun detailedFits(
        columnMillis: Long,
        subBucketMillis: Long,
        quantilesExact: Boolean,
    ): Boolean {
        if (!quantilesExact) return false
        if (columnMillis <= 0L || subBucketMillis <= 0L) return true
        return columnMillis <= subBucketMillis
    }

    /** Вертикальный штрих размаха одной колонки. */
    data class RangeStroke(val x: Float, val topY: Float, val bottomY: Float)

    /**
     * Ломаные по медианам колонок: список отрезков, каждый — точки (x, y).
     * Разрыв во времени ([segmentStart]) начинает новую ломаную: перо через
     * пропуск не идёт.
     */
    fun medianPolylines(
        x: FloatArray,
        medianY: FloatArray,
        plottable: BooleanArray,
        segmentStart: BooleanArray,
    ): List<List<Pair<Float, Float>>> {
        val out = mutableListOf<List<Pair<Float, Float>>>()
        var current = mutableListOf<Pair<Float, Float>>()
        for (i in x.indices) {
            if (!plottable[i]) {
                if (current.isNotEmpty()) { out += current; current = mutableListOf() }
                continue
            }
            if (segmentStart[i] && current.isNotEmpty()) {
                out += current
                current = mutableListOf()
            }
            current += x[i] to medianY[i]
        }
        if (current.isNotEmpty()) out += current
        return out
    }

    /**
     * Штрихи размаха: по одному на колонку, где минимум и максимум различны.
     * Колонка, у которой они совпали, размаха не имеет — её несёт медиана.
     */
    fun rangeStrokes(
        x: FloatArray,
        minY: FloatArray,
        maxY: FloatArray,
        plottable: BooleanArray,
    ): List<RangeStroke> {
        val out = mutableListOf<RangeStroke>()
        for (i in x.indices) {
            if (!plottable[i]) continue
            // Ось экрана растёт вниз: максимум величины — меньший y.
            if (minY[i] != maxY[i]) out += RangeStroke(x[i], maxY[i], minY[i])
        }
        return out
    }
}
