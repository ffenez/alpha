package app.alpha.ui.logic

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Раскладка Главной по высоте экрана.
 *
 * Страница собрана из трёх блоков: шапка с чипами, главная карточка и всё, что
 * ниже её (графики и предупреждения). Высоты первого и третьего от карточки не
 * зависят, поэтому свободная высота считается вычитанием, а не подгонкой.
 */
object MonitorLayout {

    /**
     * Сколько блоков разделено промежутком и полями: два поля страницы, два
     * промежутка между тремя блоками и два поля внутри самой карточки.
     */
    const val GAP_COUNT = 6

    /**
     * Наименьшая высота СОДЕРЖИМОГО главной карточки, dp.
     *
     * [viewport] — высота, доступная странице, [header] и [below] — измеренные
     * высоты соседних блоков, [gap] — шаг сетки отступов. Ноль означает, что
     * свободной высоты нет и карточка остаётся по своему содержимому: страница
     * в этом случае прокручивается.
     */
    fun heroContentMin(viewport: Dp, header: Dp, below: Dp, gap: Dp): Dp {
        val free = viewport - header - below - gap * GAP_COUNT
        return if (free > 0.dp) free else 0.dp
    }
}
