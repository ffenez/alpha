package app.alpha.ui.logic

import app.alpha.device.DeviceModel

/**
 * Что умеет подключённый прибор — одно правило на всё приложение.
 *
 * Проверки «спектрометр ли это» расползались по экранам поодиночке, и каждая
 * новая функция начинала с чистого листа: разбор пиков отказывался работать на
 * пластиковом сцинтилляторе, а радон и съёмка по тем же линиям — нет.
 *
 * Правило одно: спектральные выводы (пики, нуклиды, радон, радиоэлементная
 * съёмка, спектрограмма, жёсткость) требуют прибора, РАЗДЕЛЯЮЩЕГО энергии.
 * Органический пластик их не разделяет: он считает импульсы, и любая линия в
 * его спектре — свойство обработки, а не источника.
 */
object InstrumentCapability {

    /**
     * Можно ли делать выводы по форме спектра.
     *
     * @param model подключённый прибор; null — прибор неизвестен (снимок из
     *   истории, нет связи). Неизвестный НЕ запрещает: отказывать в разборе
     *   собственному снимку из-за отсутствия связи было бы ложью о данных.
     */
    fun spectral(model: DeviceModel?): Boolean = model?.isSpectrometer ?: true

    /**
     * Подогнан ли профиль обработки под этот прибор.
     *
     * У 101 и 102 вендор не публикует разрешение, и они работают на
     * консервативном значении серии. Это не отказ, но экран обязан сказать, что
     * ширина окон взята с запасом, а не измерена.
     */
    fun tunedProfile(model: DeviceModel?): Boolean = model?.resolution662 != null

    /**
     * Помещается ли окно линии в шкалу прибора.
     *
     * У линии Tl-208 (2614,5 кэВ) окно доходит почти до верха шкалы серии
     * (3 МэВ), и прибор с более низким потолком её просто не увидит. Это не
     * «линия не набрана», а «мерить нечем», и разница должна быть видна.
     */
    fun lineInScale(model: DeviceModel?, energyKeV: Float, halfWidthKeV: Float): Boolean {
        val device = model ?: return true
        return energyKeV - halfWidthKeV >= device.minEnergyKeV &&
            energyKeV + halfWidthKeV <= device.maxEnergyKeV
    }
}
