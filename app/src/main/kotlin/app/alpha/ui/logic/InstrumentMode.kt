package app.alpha.ui.logic

import app.alpha.ui.text.Strings

/**
 * Два вопроса одного прибора — и два ЗНАМЕНАТЕЛЯ, которыми они различаются.
 *
 * Раньше это были две вкладки и переключатель внутри одной из них, а всего
 * вопросов насчитывалось три. Их стало два, потому что «проверка» оказалась не
 * вопросом, а ФАЗОЙ поиска: пока прибор несут, важно «теплее или холоднее»;
 * как только он остановился, тот же самый счёт против того же самого
 * знаменателя дозревает до вывода «отличается» или «отличия не найдено».
 * Отдельный режим для этого не нужен — нужна полоска «сколько ещё держать».
 *
 * Знаменатель поиска выбирается сам ([app.alpha.ui.logic.SearchReferences]):
 * поставлена точка отсчёта — считаем от неё, нет — от фона места.
 */
enum class InstrumentMode(val id: String) {

    /** Знаменатель — медиана фона ЭТОГО МЕСТА; величина — мощность дозы. */
    OBSERVE("observe"),

    /**
     * Знаменатель — точка отсчёта, а без неё фон места; величина — счёт.
     *
     * Счёт, а не доза: он набирает статистику в разы быстрее, и именно им
     * водят прибором.
     */
    SEARCH("search"),
    ;

    /** Название режима на языке интерфейса. */
    fun title(s: Strings): String = when (this) {
        OBSERVE -> s.modeObserve
        SEARCH -> s.modeSearchShort
    }

    companion object {
        /**
         * Режим по сохранённому идентификатору.
         *
         * Неизвестное значение — наблюдение: это состояние, в котором прибор
         * ничего не требует от человека, и открыть его после сбоя настройки
         * безопаснее всего.
         */
        fun of(id: String?): InstrumentMode = entries.firstOrNull { it.id == id } ?: OBSERVE
    }
}
