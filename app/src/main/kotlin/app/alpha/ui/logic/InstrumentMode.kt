package app.alpha.ui.logic

import app.alpha.ui.text.Strings

/**
 * Три вопроса одного прибора — и три ЗНАМЕНАТЕЛЯ, которыми они различаются.
 *
 * Раньше это были две вкладки и переключатель внутри одной из них. Вопрос при
 * этом везде один — «много ли здесь», — и меняется в нём только то, с чем
 * сравнивают. Поэтому режим один и живёт в одном месте (макет
 * `docs/design/one-instrument.html`).
 *
 * Порядок отвечает порядку работы: сначала смотрят на место, потом ищут в нём
 * источник, потом сверяют место с эталоном.
 */
enum class InstrumentMode(val id: String) {

    /** Знаменатель — медиана фона ЭТОГО МЕСТА; величина — мощность дозы. */
    OBSERVE("observe"),

    /** Знаменатель — точка отсчёта, поставленная рукой; величина — счёт. */
    SEARCH("search"),

    /** Знаменатель — записанный фон места; вопрос про отличие, а не про «теплее». */
    VERIFY("verify"),
    ;

    /** Название режима на языке интерфейса. */
    fun title(s: Strings): String = when (this) {
        OBSERVE -> s.modeObserve
        SEARCH -> s.modeSearchShort
        VERIFY -> s.modeVerifyShort
    }

    companion object {
        /**
         * Режим по сохранённому идентификатору.
         *
         * Неизвестное значение — наблюдение: это состояние, в котором прибор
         * ничего не требует от человека, и открыть его после сбоя настройки
         * безопаснее всего.
         */
        fun of(id: String?): InstrumentMode = entries.firstOrNull { it.id == id } ?: OBSERVE
    }
}
