package app.alpha.ui.logic

import app.alpha.ui.text.MonitorRu
import app.alpha.ui.text.MonitorStrings

/**
 * Абсолютный уровень мощности дозы — то немногое, ради чего экран имеет право
 * кричать.
 *
 * ## Зачем отдельно от обычного фона места
 *
 * Всё остальное на Главной — сравнение с ЭТИМ местом: «обычно здесь», «выше
 * обычного», «выше вашего порога». Это ответы на вопрос «изменилось ли что-то
 * у меня дома», и они верны хоть в подвале, хоть в самолёте. Здесь вопрос
 * другой и он не зависит ни от места, ни от настроек: сколько наберётся, если
 * остаться. На этот вопрос отвечают числа дозиметрии, а не статистика профиля.
 *
 * ## Пороги названы дозой, а не словом
 *
 * Приложение не объявляет уровень опасным — оно называет, что произойдёт со
 * временем: за сутки здесь наберётся столько-то, за час — столько-то. Дальше
 * человек решает сам; инструмент говорит, чем измеряется его решение.
 */
enum class DoseAlarmLevel {
    /** Ничего, ради чего стоит занимать верх экрана. */
    NONE,

    /** Уровень заметно выше природного фона: стоит разобраться и уйти. */
    ELEVATED,

    /** Уровень, при котором единственное разумное действие — уйти. */
    LEAVE,
}

object DoseAlarm {

    /**
     * Природный фон открытой местности, мкЗв/ч.
     *
     * **Инженерный параметр**: 0,15 мкЗв/ч — типичное значение на равнине вне
     * помещений; служит ЗНАМЕНАТЕЛЕМ отношения, которое печатается рядом с
     * заголовком, и потому названо, а не подразумевается.
     */
    const val NATURAL_BACKGROUND_MICRO_SVH = 0.15f

    /**
     * Порог «повышенный уровень», мкЗв/ч.
     *
     * **Инженерный параметр**: 10 мкЗв/ч — около семидесяти природных фонов.
     * За неделю непрерывного пребывания здесь набирается 1,7 мЗв, то есть
     * больше годового предела для населения (1 мЗв/год, НРБ-99/2009 и МКРЗ).
     * Ниже этого значения обычная жизнь даёт сопоставимые числа — в самолёте,
     * в горах, на гранитной набережной, — и кричать там не о чем.
     */
    const val ELEVATED_MICRO_SVH = 10f

    /**
     * Порог «уходите отсюда», мкЗв/ч.
     *
     * **Инженерный параметр**: 1000 мкЗв/ч = 1 мЗв/ч — за ОДИН час здесь
     * набирается годовой предел для населения целиком. Это же верх шкалы
     * бытовых сцинтилляционных дозиметров: выше прибор перестаёт отвечать на
     * вопрос «сколько», и единственное, что остаётся сказать, — уходить.
     */
    const val LEAVE_MICRO_SVH = 1000f

    fun of(doseRateMicroSvH: Float?): DoseAlarmLevel = when {
        doseRateMicroSvH == null -> DoseAlarmLevel.NONE
        doseRateMicroSvH >= LEAVE_MICRO_SVH -> DoseAlarmLevel.LEAVE
        doseRateMicroSvH >= ELEVATED_MICRO_SVH -> DoseAlarmLevel.ELEVATED
        else -> DoseAlarmLevel.NONE
    }

    /** Заголовок уровня; null — заголовка нет, и экран молчит. */
    fun headline(level: DoseAlarmLevel, s: MonitorStrings = MonitorRu): String? = when (level) {
        DoseAlarmLevel.NONE -> null
        DoseAlarmLevel.ELEVATED -> s.alarmElevated
        DoseAlarmLevel.LEAVE -> s.alarmLeave
    }

    /**
     * Строка под заголовком: чем измеряется вывод.
     *
     * У повышенного уровня это отношение к природному фону — со знаменателем,
     * как требует правило вывода; у «уходите» — доза за час, потому что
     * решение принимается именно по ней.
     */
    fun note(
        level: DoseAlarmLevel,
        doseRateMicroSvH: Float?,
        s: MonitorStrings = MonitorRu,
    ): String? = when (level) {
        DoseAlarmLevel.NONE -> null
        DoseAlarmLevel.ELEVATED -> doseRateMicroSvH?.let {
            s.alarmElevatedNote(timesNatural(it))
        }
        DoseAlarmLevel.LEAVE -> s.alarmLeaveNote
    }

    /**
     * «×70» — во сколько раз выше природного фона.
     *
     * Округление к БЛИЖАЙШЕМУ шагу, а не отбрасывание: 30 мкЗв/ч — это ровно
     * двести природных фонов, и «×190» из-за двоичного представления 0,15
     * было бы неправдой на ровном месте.
     */
    fun timesNatural(doseRateMicroSvH: Float): String {
        val times = doseRateMicroSvH / NATURAL_BACKGROUND_MICRO_SVH
        val step = when {
            times >= 1000 -> 100
            times >= 100 -> 10
            else -> 1
        }
        return "×${Math.round(times / step) * step}"
    }
}
