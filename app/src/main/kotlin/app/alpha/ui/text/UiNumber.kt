package app.alpha.ui.text

/**
 * Десятичный разделитель ИНТЕРФЕЙСА: «0,17» по-русски и «0.17» по-английски.
 *
 * Локаль телефона здесь ни при чём — язык интерфейса приложение выбирает само
 * (`AppLanguage`), и английский экран с «0,17» читается как перечисление, а не
 * как число. Числа при этом всегда форматируются через `Locale.US`, чтобы
 * системная локаль не подменила разделитель молча, а нужный ставится уже
 * здесь.
 *
 * Разделитель хранится процессом, а не передаётся аргументом: числа собираются
 * в чистых функциях `ui/logic` и `analysis`, у которых нет доступа ни к
 * композиции, ни к настройкам, и протаскивание языка через полсотни подписей
 * ничего не уточняет. Значение выставляется один раз рядом с выбором языка
 * ([apply]); значение по умолчанию — русское.
 */
object UiNumber {

    @Volatile
    private var separator: Char = ','

    /** Вызывается там же, где выбирается язык интерфейса. */
    fun apply(language: AppLanguage) {
        separator = if (language == AppLanguage.EN) '.' else ','
    }

    /** Только для тестов: вернуть исходное состояние. */
    fun reset() {
        separator = ','
    }

    fun decimal(text: String): String =
        if (separator == '.') text else text.replace('.', separator)
}

/**
 * Точка в уже отформатированном числе → разделитель языка интерфейса.
 * Ставится в конце цепочки: `String.format(Locale.US, "%.2f", v).uiDecimal()`.
 */
fun String.uiDecimal(): String = UiNumber.decimal(this)
