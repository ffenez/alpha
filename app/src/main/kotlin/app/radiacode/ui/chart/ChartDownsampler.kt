package app.radiacode.ui.chart

import app.radiacode.ui.logic.ChartSeriesModel

/**
 * Сколько колонок рисовать и какой они ширины — по ФАКТИЧЕСКОЙ ширине поля.
 *
 * ## Что было не так
 *
 * Ширину колонки задавал ПРОЧИТАННЫЙ ДИАПАЗОН — окно плюс запас с обеих сторон,
 * который читается ради мгновенного перелистывания. На пятиминутном окне запас
 * даёт больше двух часов, делённых на две сотни колонок, — то есть колонку в
 * тридцать семь секунд. Триста измерений, лежащих в том же снимке посекундно,
 * превращались в восемь узлов: график был честен по числам и почти пуст по
 * форме. Запас чтения — решение о производительности, и определять разрешение
 * картинки он не имеет права.
 *
 * ## Правило
 *
 * Колонок столько, сколько их видно: ширина поля, делённая на
 * [PIXELS_PER_COLUMN]. Но не больше, чем есть агрегатов, — иначе картинка
 * заявляла бы разрешение, которого у данных нет: колонка уже подсекундного
 * агрегата не может отличаться от него ничем, кроме пустот между колонками.
 *
 * ## Почему прореживание сохраняет пики
 *
 * Колонка несёт min, max, квантили и точные моменты экстремумов
 * ([ChartSeriesModel.fold]), поэтому узкий настоящий всплеск внутри колонки
 * остаётся и числом, и маркером над полем. Простое «каждое N-е измерение»
 * теряет ровно его — то есть ровно то, ради чего график открывают (ТЗ §10).
 */
object ChartDownsampler {

    /**
     * Пикселей на колонку.
     *
     * **Инженерный параметр**: два. Линия толщиной 2,2 dp, и колонка уже двух
     * пикселей не даёт нового изгиба — она даёт лишнюю работу на каждом кадре
     * жеста. ТЗ (§10) просит 1–4 примитива на горизонтальный пиксель: при двух
     * пикселях на колонку выходит около двух (медиана и её конверт).
     */
    const val PIXELS_PER_COLUMN = 2f

    /**
     * Потолок числа колонок.
     *
     * **Инженерный параметр**: тысяча. Ширина телефона в пикселях — около
     * тысячи, планшета в ландшафте — вдвое больше; потолок ограничивает не
     * экран, а стоимость кадра, если поле окажется неожиданно широким.
     */
    const val MAX_COLUMNS = 1_000

    /**
     * Потолок числа колонок ГЕОМЕТРИИ — она строится шире видимого окна
     * (`ChartGesture.HEADROOM_FRACTION`), чтобы жест двигал готовую картинку.
     *
     * **Инженерный параметр**: вдвое больше [MAX_COLUMNS] плюс запас на
     * округление. Потолок ниже нужного молча обрезал бы НАРИСОВАННЫЙ диапазон
     * с одного края — то есть открывал бы пустоту ровно там, ради чего запас и
     * считается.
     */
    const val MAX_RENDERED_COLUMNS = 2 * MAX_COLUMNS + 100

    /** Если ширина поля ещё не измерена — прежняя геометрия P0. */
    const val DEFAULT_COLUMNS = ChartSeriesModel.MAX_BUCKETS

    /**
     * Колонок в сглаженном виде.
     *
     * **Инженерный параметр**: шестьдесят. Сглаженный вид показывает не сами
     * измерения, а медиану колонки с квантильными конвертами — то есть разброс
     * ВНУТРИ колонки, и в колонке должно быть чему разбрасываться. Раньше
     * ширину колонки здесь задавал прочитанный диапазон, и «сглаженность»
     * получалась случайно: на пятиминутном окне колонка выходила в тридцать
     * семь секунд, на часовом — в полторы минуты, без всякого правила. Теперь
     * это правило: шестьдесят колонок на любом окне, около восемнадцати
     * пикселей на колонку у телефона, и вид узнаваем одинаково везде.
     *
     * Разрешение данных при этом не выдумывается: колонка никогда не уже
     * агрегата, поэтому на минутном окне сглаженный вид совпадает с подробным
     * — сглаживать там нечего, и притворяться иначе картинка не будет.
     */
    const val SMOOTHED_COLUMNS = 60

    /**
     * Колонок для поля шириной [widthPx].
     *
     * @param spanMillis длительность видимого окна.
     * @param subBucketMillis ширина подсекундного агрегата в снимке — граница,
     *   ниже которой у данных больше нет разрешения.
     */
    fun columnCount(widthPx: Float, spanMillis: Long, subBucketMillis: Long): Int {
        if (spanMillis <= 0L) return 1
        val byWidth = if (widthPx <= 0f) {
            DEFAULT_COLUMNS
        } else {
            (widthPx / PIXELS_PER_COLUMN).toInt()
        }
        val byData = if (subBucketMillis <= 0L) {
            byWidth
        } else {
            (spanMillis / subBucketMillis).toInt()
        }
        return minOf(byWidth, byData).coerceIn(1, MAX_COLUMNS)
    }

    /**
     * Ширина колонки для видимого окна на поле шириной [widthPx].
     *
     * Никогда не уже агрегата: колонки, в которую по построению попадает не
     * больше одного агрегата, между соседями возникали бы пустоты, и ровный
     * ряд измерений выглядел бы решёткой из пропусков.
     */
    fun columnMillis(
        widthPx: Float,
        spanMillis: Long,
        subBucketMillis: Long,
        /** Сглаженный вид держит [SMOOTHED_COLUMNS] колонок на любом окне. */
        smoothed: Boolean = false,
    ): Long {
        val columns = columnCount(widthPx, spanMillis, subBucketMillis)
        val even = (spanMillis / columns).coerceAtLeast(1L)
        val fine = maxOf(even, subBucketMillis.coerceAtLeast(1L))
        if (!smoothed) return fine
        val coarse = (spanMillis / SMOOTHED_COLUMNS).coerceAtLeast(1L)
        return maxOf(fine, coarse)
    }

    /**
     * Стоит ли рисовать отдельные измерения точками.
     *
     * Точки имеют смысл, только когда колонка ШИРЕ агрегата: тогда внутри
     * колонки действительно что-то усреднено и точки показывают, что именно.
     * Когда колонка равна агрегату, линия и так идёт по измерениям, и точки
     * повторяли бы её узлы, притворяясь вторым слоем данных.
     */
    fun rawDotsVisible(columnMillis: Long, subBucketMillis: Long): Boolean =
        columnMillis > subBucketMillis &&
            columnMillis <= ChartSeriesModel.RAW_DOTS_MAX_BUCKET_MILLIS
}
