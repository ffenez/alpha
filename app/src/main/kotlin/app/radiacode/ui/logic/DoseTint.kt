package app.radiacode.ui.logic

import app.radiacode.baseline.Baseline

/**
 * Цвет главного числа — от обычного для этого места до заметно выше него.
 *
 * ## Что означает цвет
 *
 * Только ОТНОШЕНИЕ к обычному фону этого места и к порогу, который человек
 * задал сам. Это не шкала опасности: приложение нигде не говорит «норма» или
 * «опасно», и цвет не имеет права сказать то, чего не говорят слова.
 *
 * Поэтому у шкалы всего две точки привязки, и обе — не выдуманные:
 *  - **низ** — верхняя граница обычного диапазона места (P90). Всё, что внутри
 *    диапазона, окрашено одинаково: внутри него значения не «лучше» и не
 *    «хуже» друг друга, они одинаково обычные.
 *  - **верх** — порог тревоги. Дальше цвет не меняется: за порогом решает уже
 *    не оттенок, а вывод словами.
 *
 * ## Когда цвета нет
 *
 * Пока для места нет обычного диапазона, сравнивать не с чем — число остаётся
 * обычного цвета. Крашеное число без основания сравнения означало бы шкалу,
 * которой не существует.
 */
object DoseTint {

    /**
     * Положение значения между «обычно здесь» и порогом: 0 — внутри обычного
     * диапазона, 1 — на пороге и выше. Null — сравнивать не с чем.
     */
    fun fraction(
        doseMicroSvH: Float?,
        baseline: Baseline?,
        alarmMicroSvH: Float?,
    ): Float? = of(
        value = doseMicroSvH,
        usualHigh = baseline?.doseHighMicroSvH,
        top = alarmMicroSvH,
    )

    /**
     * То же самое для любой величины со своим «обычно здесь».
     *
     * Поиск сравнивает счёт с ЗАПИСАННЫМ фоном, Главная — дозу с обычным
     * диапазоном места. Величины разные, правило одно, и написано оно один
     * раз: два экрана, красящие числа по-разному, означали бы две разные
     * шкалы под одинаковыми цветами.
     */
    fun of(value: Float?, usualHigh: Float?, top: Float?): Float? {
        val current = value ?: return null
        if (!current.isFinite()) return null
        val high = usualHigh ?: return null
        if (!high.isFinite() || high <= 0f) return null
        if (current <= high) return 0f
        // Верх ниже обычного — не шкала, а противоречие: тогда единственная
        // честная привязка это само «обычно».
        val ceiling = top?.takeIf { it.isFinite() && it > high } ?: (high * FALLBACK_TOP)
        return ((current - high) / (ceiling - high)).coerceIn(0f, 1f)
    }

    /**
     * Во сколько раз выше P90 стоит верх шкалы, когда порога тревоги нет.
     * **Инженерный параметр**: вдвое. Тот же множитель, которым «выше
     * обычного» отличается от «сильно выше» в остальных местах приложения, и
     * он не выдумывает нового смысла — просто задаёт, где цвет насытится.
     */
    const val FALLBACK_TOP = 2f
}
