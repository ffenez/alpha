package app.radiacode.ui.logic

/**
 * Один шаблон результата для всех аналитических экранов.
 *
 * ## Порядок и почему он такой
 *
 * **Что получилось → на чём это измерено → что это значит → чего это не
 * значит.** Раньше первым, что видел человек, было `−0,29 сейчас` или
 * `значимость −12,6`: внутренний статистический остаток в роли ответа. Число
 * со знаком минус в этой роли не читается никак — ни «мало», ни «много», ни
 * «ничего нет», — а между тем означает оно ровно последнее.
 *
 * Числа не выброшены и не округлены: signed net, σ и значимость лежат в
 * [details] и открываются одним нажатием. Упрощено ПРЕДСТАВЛЕНИЕ результата,
 * а не математика под ним.
 */
data class AnalyticsResult(
    /** Категориальный ответ: «Линия не выделяется». */
    val verdict: String,
    val tone: ResultTone,
    /** «13 часовых интервалов · охват 11 ч» — сколько данных и за какой срок. */
    val measurement: String?,
    /** Что этот ответ означает, обычными словами. */
    val meaning: String,
    /** Чего он НЕ означает: граница метода стоит рядом с выводом. */
    val limitation: String,
    /** Технический уровень: то же самое числами. */
    val details: List<WhyLine>,
)

/**
 * Цвет вывода — состояние сравнения, а не приговор месту.
 *
 * [NOTABLE] значит «нашлось, на что смотреть», а не «опасно»: приложение не
 * выносит суждений о безопасности ни цветом, ни словом.
 */
enum class ResultTone { NOTABLE, PLAIN, UNKNOWN }

/**
 * Три исхода, к которым сводится любой из этих экранов.
 *
 * Отрицательное нетто отдельным исходом НЕ является: «в окне меньше, чем в
 * соседних участках спектра» — это тот же ответ «избытка нет», просто
 * оценка континуума в этот раз оказалась выше самой ROI. Разница видна в
 * подробностях, где стоит число со знаком.
 */
enum class ExcessVerdict {
    /** Данных пока не хватает, чтобы вообще что-то сказать. */
    NO_DATA,

    /** Избытка над локальным фоном спектра не видно. */
    NOT_RESOLVED,

    /** Избыток устойчив: нетто отличается от нуля больше чем на порог. */
    EXCESS,
    ;

    companion object {
        /**
         * Порог значимости, с которого об избытке вообще говорят.
         *
         * **Инженерный параметр**, тот же, что у ряда линии
         * ([app.radiacode.analysis.NuclideTrend.MIN_SIGNIFICANCE]): считается
         * ОДНО заранее названное окно, поэтому поправка на множественность
         * проверок не нужна, а три σ — обычная граница для «отличается от
         * нуля» при пуассоновском счёте.
         */
        fun of(significance: Float?, minSignificance: Float): ExcessVerdict = when {
            significance == null || !significance.isFinite() -> NO_DATA
            significance >= minSignificance -> EXCESS
            else -> NOT_RESOLVED
        }
    }
}
