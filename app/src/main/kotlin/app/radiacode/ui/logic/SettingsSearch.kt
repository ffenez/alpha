package app.radiacode.ui.logic

import java.util.Locale

/**
 * Поиск по настройкам: слово, которое человек помнит, → раздел, где это лежит.
 *
 * ## Зачем
 *
 * Разделов семь, и это уже больше, чем держится в голове. Человек помнит не
 * структуру, а слово: «звук», «фон», «язык», «батарея». Пока поиска нет, он
 * открывает разделы по очереди — и половина попыток не туда.
 *
 * ## Почему синонимы, а не поиск по подписям
 *
 * Подпись настройки и слово, которым её называют про себя, — разные вещи:
 * «Отклик» никто не ищет словом «отклик», ищут «звук» и «вибрация». Индекс
 * поэтому хранит СЛОВА, по которым настройку ищут, а не текст, которым она
 * подписана; подпись приходит из каталога строк и остаётся на языке
 * интерфейса.
 */
object SettingsSearch {

    /** Одна находка: что нашли и в каком разделе это лежит. */
    data class Hit(
        /** Идентификатор раздела, куда ведёт находка. */
        val categoryId: String,
        /** Что именно нашли — подпись настройки на языке интерфейса. */
        val title: String,
        /** Где это лежит — название раздела. */
        val section: String,
    )

    /**
     * Запись индекса: настройка, её раздел и слова, по которым её ищут.
     *
     * Слова хранятся уже приведёнными к нижнему регистру — приводить их на
     * каждый ввод символа незачем.
     */
    data class Entry(
        val categoryId: String,
        val title: String,
        val section: String,
        val keywords: List<String>,
    )

    /**
     * Находки по запросу; пустой запрос — пустой список (не «всё подряд»:
     * список всех настроек человек и так видит на экране).
     *
     * Совпадением считается начало слова, а не любое вхождение: «он» не должно
     * находить «фон» и «отклик» — иначе после второй буквы список перестаёт
     * помогать.
     */
    fun find(query: String, index: List<Entry> = emptyList()): List<Hit> {
        val needle = normalize(query)
        if (needle.isEmpty()) return emptyList()
        return index
            .filter { entry ->
                entry.keywords.any { it.startsWith(needle) } ||
                    normalize(entry.title).split(' ').any { it.startsWith(needle) }
            }
            .map { Hit(it.categoryId, it.title, it.section) }
            .distinctBy { it.categoryId to it.title }
    }

    /** Регистр и лишние пробелы значения не имеют, «ё» пишут и так и так. */
    fun normalize(value: String): String =
        value.trim().lowercase(Locale.ROOT).replace('ё', 'е')
}
