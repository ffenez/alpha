package app.radiacode.ui.logic

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/**
 * Состояние «Наведения» на время жизни приложения.
 *
 * ## Зачем не `remember` в экране
 *
 * Точку отсчёта ставит ЧЕЛОВЕК, и она — единственное число на этом экране,
 * которое он выбрал сам. Пока состояние жило в композиции экрана, переход на
 * другую вкладку и обратно стирал её молча: человек возвращался и обнаруживал,
 * что сравнивать снова не с чем, хотя ничего не отменял. Здесь же держится и
 * зафиксированный максимум — по той же причине.
 *
 * Лента и окна при этом честно стареют: они отфильтровываются по возрасту на
 * первом же новом измерении, так что вернувшийся экран не рисует минутной
 * давности картинку как свежую.
 */
class NavigateSession {
    var state: NavigateState by mutableStateOf(NavigateState())
}
