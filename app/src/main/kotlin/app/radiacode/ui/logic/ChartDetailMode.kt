package app.radiacode.ui.logic

/**
 * Два способа показать ОДНИ И ТЕ ЖЕ измерения.
 *
 * ## Что было сломано
 *
 * Ширину колонки задавал не видимый интервал, а ЗАГРУЖЕННЫЙ — окно плюс час
 * запаса с каждой стороны, который читается ради мгновенного перелистывания.
 * На пятиминутном окне это давало колонку в 37 секунд: триста измерений
 * превращались в восемь узлов с широкими квантильными полосами, хотя сами
 * измерения лежали в том же снимке посекундно. Запас чтения — решение о
 * ПРОИЗВОДИТЕЛЬНОСТИ, и менять из-за него разрешение картинки он не имеет
 * права.
 *
 * ## Как теперь
 *
 * Данные читаются один раз и одинаково для обоих режимов; различается только
 * последний шаг — как из подсекундных агрегатов собирается картинка:
 *
 *  - [DETAILED] складывает их в колонки шириной с ВИДИМОЕ окно, поделённое на
 *    число колонок. На коротком окне в колонке оказывается одно измерение, и
 *    линия идёт ровно по измерениям; на длинном колонка широкая, и линия
 *    ведётся по её крайним значениям — прореживание, сохраняющее форму, где
 *    пик и провал остаются, а не усредняются.
 *  - [SMOOTHED] оставляет прежнюю картинку: медиана колонки и квантильные
 *    конверты Q25–Q75 и Q10–Q90 — описание разброса измерений внутри колонки.
 *
 * Статистика окна (P10 · медиана · P90 · n) считается по подсекундным
 * агрегатам и от режима НЕ зависит: режим меняет представление, а не данные.
 */
enum class ChartDetailMode {
    DETAILED,
    SMOOTHED,
    ;

    val id: String get() = name.lowercase()

    companion object {
        val DEFAULT = DETAILED

        fun of(id: String?): ChartDetailMode =
            entries.firstOrNull { it.id == id } ?: DEFAULT
    }
}
