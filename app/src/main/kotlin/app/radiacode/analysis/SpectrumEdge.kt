package app.radiacode.analysis

/**
 * Крайний канал спектра — граница диапазона, а не точка спектра.
 *
 * ## Что наблюдается
 *
 * В последнем канале RadiaCode регулярно оказывается счёт, на порядки
 * превышающий соседние каналы. На графике это выглядело как узкий «пик» у
 * правого края (≈2,8 МэВ), которого в природе нет: линия шла вниз, а в самой
 * последней точке отвесно взлетала.
 *
 * ## Почему это не пик — независимо от причины
 *
 * Здесь СОЗНАТЕЛЬНО не утверждается механизм. Публичной документации, которая
 * говорила бы «прошивка складывает в последний канал всё, что вышло за
 * диапазон», найти не удалось; сообщество объясняет это именно так, и для
 * многоканальных анализаторов это обычное поведение, но подтвердить это как
 * факт нечем. Косвенное подтверждение того, что канал особенный, есть у самого
 * вендора: в официальном приложении появилась настройка «не показывать
 * последний канал», а затем правка ошибки, возникавшей при её включении
 * (changelog RadiaCode, прошивка 1.09).
 *
 * Для решения механизм и не нужен — достаточно двух фактов:
 *
 * 1. **Это край диапазона.** Всё, что происходило выше верхней границы, прибор
 *    в этой шкале не различает, поэтому содержимое крайнего канала нельзя
 *    читать как «столько импульсов имели такую энергию».
 * 2. **Один канал не может быть фотопиком.** По собственной модели разрешения
 *    приложения ([PeakDetection.fwhmKeV]) FWHM около 2800 кэВ ≈ 109 кэВ, то
 *    есть десятки каналов. Всплеск шириной в один канал не является пиком ни
 *    при каком объяснении его происхождения.
 *
 * ## Что делает приложение
 *
 * Крайний канал не входит ни в кривую, ни в масштаб оси, ни в поиск пиков, ни
 * в сравнение формы, ни в энергетические окна. Его содержимое НЕ отбрасывается
 * молча: экран показывает его отдельной строкой — это диагностическая
 * информация о том, что прибор что-то регистрировал у верхней границы.
 */
object SpectrumEdge {

    /**
     * Сколько каналов у верхнего края не считаются точками спектра.
     *
     * **Инженерный параметр.** Один — ровно тот канал, который является
     * границей шкалы. Расширять «на всякий случай» нельзя: каждый лишний
     * отброшенный канал это выброшенные измерения.
     */
    const val EDGE_CHANNELS = 1

    const val EXPLANATION =
        "Последний канал — граница энергетической шкалы. Что происходило выше неё, " +
            "прибор в этой шкале не различает, поэтому крайний канал не показан на " +
            "кривой и не участвует в поиске пиков: всплеск шириной в один канал не " +
            "является пиком."

    /** Последний канал, который считается точкой спектра. */
    fun lastAnalysableChannel(channelCount: Int): Int =
        (channelCount - 1 - EDGE_CHANNELS).coerceAtLeast(0)

    /** Каналы, которые считаются спектром; пусто, если их нет вовсе. */
    fun analysable(channelCount: Int): IntRange = 0..lastAnalysableChannel(channelCount)

    /** Импульсы в крайних каналах — то, что показывается отдельной строкой. */
    fun edgeCounts(counts: List<Int>): Long {
        if (counts.size <= EDGE_CHANNELS) return 0L
        var sum = 0L
        for (i in (lastAnalysableChannel(counts.size) + 1) until counts.size) sum += counts[i]
        return sum
    }

    /** [edgeCounts] для массива каналов. */
    fun edgeCounts(counts: IntArray): Long {
        if (counts.size <= EDGE_CHANNELS) return 0L
        var sum = 0L
        for (i in (lastAnalysableChannel(counts.size) + 1) until counts.size) sum += counts[i]
        return sum
    }

    /** Копия спектра без крайних каналов — для анализа формы. */
    fun withoutEdge(counts: DoubleArray): DoubleArray =
        if (counts.size <= EDGE_CHANNELS) counts
        else counts.copyOfRange(0, lastAnalysableChannel(counts.size) + 1)
}
