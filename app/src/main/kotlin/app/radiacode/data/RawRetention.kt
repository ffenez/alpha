package app.radiacode.data

/**
 * Хранение сырых 1 Гц измерений: правило среза.
 *
 * ## Почему это НАСТРОЙКА с умолчанием «хранить всё»
 *
 * Уборка журнала — единственное место приложения, где данные исчезают, и она
 * всегда была явным действием человека. Автоматическое удаление по возрасту —
 * второе такое место, поэтому оно существует только по явному выбору владельца
 * и по умолчанию выключено. Молча «оптимизировать» чужие измерения нельзя.
 *
 * ## Что переживает срез
 *
 * Минутные агрегаты и часовые скетчи (ADR 004), сводки сессий, снимки спектра,
 * треки и события — всё остаётся: долгие окна графиков и статистика мест
 * строятся по ним. Теряется только сырая посекундная детализация старше среза:
 * деталка старой сессии перестанет показывать точный ряд, а «сверить с сырыми»
 * ограничится оставшимся.
 *
 * ## Нижняя граница
 *
 * Обычный фон профиля читает сырые минутные корзины за 14 суток — срез короче
 * этого ломал бы статистику мест, поэтому он невозможен по построению.
 */
object RawRetention {

    /** «Хранить всё» — значение по умолчанию. */
    const val KEEP_ALL_DAYS = 0

    /** Минимальный срез: окно обычного фона (14 сут) с двойным запасом. */
    const val MIN_DAYS = 30

    val OPTIONS: List<Int> = listOf(KEEP_ALL_DAYS, 90, MIN_DAYS)

    /** Хранимое значение может прийти любым — чинится чтением, а не падением. */
    fun sanitize(days: Int): Int = when {
        days <= KEEP_ALL_DAYS -> KEEP_ALL_DAYS
        days < MIN_DAYS -> MIN_DAYS
        else -> days
    }

    /** Отметка, старше которой сырые записи срезаются; null = не срезать. */
    fun cutoffMillis(nowMillis: Long, days: Int): Long? {
        val clean = sanitize(days)
        if (clean == KEEP_ALL_DAYS) return null
        return nowMillis - clean * 24L * 3_600_000L
    }
}
