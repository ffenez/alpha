package app.radiacode.service

/**
 * Последние такты опроса — покадровая запись того, что происходит между
 * прибором и базой.
 *
 * ## Зачем
 *
 * «Нет новых данных · 29 с» при зелёном кружке связи чинится третий раз, и
 * каждый раз по РАССУЖДЕНИЮ о коде, а не по наблюдению: прибора у меня нет,
 * а на экране видно только следствие. Кандидатов на причину как минимум три,
 * и они дают одинаковую картину:
 *
 * 1. записи приходят, но с метками в прошлом (уехала база времени прибора);
 * 2. записи приходят, но НЕ ПИШУТСЯ — уникальный индекс `samples.timestamp`
 *    молча отбрасывает строку, чья метка уже занята (`onConflict = IGNORE`);
 * 3. записи не приходят вовсе — прибор не отвечает на опрос.
 *
 * Различить их можно ровно одним снимком: сколько записей вернул ответ, какая
 * у новейшей метка, сколько строк реально легло в базу. Трасса это и хранит.
 *
 * ## Свойства
 *
 * Кольцо на [CAPACITY] тактов — это ~2 минуты при опросе 4 раза в секунду,
 * ровно тот отрезок, на котором человек замечает надпись и снимает отчёт.
 * Ничего, кроме чисел о самом обмене: ни координат, ни дозы, ни счёта —
 * отладочный архив и так обещает, что рядов измерений в нём нет.
 */
class StreamTrace {

    /**
     * @param atMillis момент, когда ответ разобран (часы телефона).
     * @param records сколько записей вернул ответ.
     * @param newestAgeMillis возраст новейшей записи ответа; null — записей нет.
     * @param correctionMillis поправка базы времени прибора на этот момент.
     * @param inserted сколько строк реально добавилось в `samples`.
     * @param dropped сколько строк отброшено уникальным индексом.
     */
    data class Tick(
        val atMillis: Long,
        val records: Int,
        val newestAgeMillis: Long?,
        val correctionMillis: Long,
        val inserted: Int,
        val dropped: Int,
    )

    private val ticks = ArrayDeque<Tick>()

    @Synchronized
    fun add(tick: Tick) {
        ticks.addLast(tick)
        while (ticks.size > CAPACITY) ticks.removeFirst()
    }

    @Synchronized
    fun snapshot(): List<Tick> = ticks.toList()

    /** Отброшено строк за сеанс — то, чего не видно ни на экране, ни в логах. */
    @Synchronized
    fun droppedTotal(): Int = ticks.sumOf { it.dropped }

    companion object {
        const val CAPACITY = 480
    }
}
